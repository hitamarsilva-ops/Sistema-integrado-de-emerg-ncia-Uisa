// Helper: Determine current active shift dynamically
export function getCurrentActiveShift(now: Date = new Date()): {
  activeShift: BrigadeShift;
  hoursLabel: string;
  isPeakDaytime: boolean;
} {
  const hour = now.getHours();
  const minutes = now.getMinutes();
  const totalMinutes = hour * 60 + minutes;

  // Turno A: 00:20 (20 min) até 08:20 (500 min)
  if (totalMinutes >= 20 && totalMinutes < 500) {
    return {
      activeShift: 'turno_a',
      hoursLabel: 'Turno A (00:20 às 08:20)',
      isPeakDaytime: false,
    };
  }

  // Turno B: 08:20 (500 min) até 16:20 (980 min)
  if (totalMinutes >= 500 && totalMinutes < 980) {
    return {
      activeShift: 'turno_b',
      hoursLabel: 'Turno B (08:20 às 16:20)',
      isPeakDaytime: true,
    };
  }

  // Turno C: 16:20 (980 min) até 00:20 (20 min do dia seguinte)
  return {
    activeShift: 'turno_c',
    hoursLabel: 'Turno C (16:20 às 00:20)',
    isPeakDaytime: false,
  };
}

// Helper: Check training status
export function getTrainingStatus(trainingExpiryDate?: string): {
  status: 'valido' | 'alerta_30d' | 'vencido';
  label: string;
  badgeClass: string;
  daysRemaining: number;
} {
  if (!trainingExpiryDate) {
    return {
      status: 'vencido',
      label: 'Sem Validade',
      badgeClass: 'bg-red-950/80 text-red-300 border-red-700',
      daysRemaining: -999,
    };
  }

  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const expiry = new Date(trainingExpiryDate + 'T00:00:00');
  const diffTime = expiry.getTime() - today.getTime();
  const daysRemaining = Math.ceil(diffTime / (1000 * 60 * 60 * 24));

  if (daysRemaining < 0) {
    return {
      status: 'vencido',
      label: `Vencido (${Math.abs(daysRemaining)}d atrás)`,
      badgeClass: 'bg-red-950/90 text-red-300 border-red-700 font-semibold',
      daysRemaining,
    };
  }

  if (daysRemaining <= 30) {
    return {
      status: 'alerta_30d',
      label: `Vence em ${daysRemaining}d`,
      badgeClass: 'bg-amber-950/90 text-amber-300 border-amber-700 font-semibold',
      daysRemaining,
    };
  }

  return {
    status: 'valido',
    label: `Válido (${daysRemaining}d)`,
    badgeClass: 'bg-emerald-950/70 text-emerald-300 border-emerald-700',
    daysRemaining,
  };
}
